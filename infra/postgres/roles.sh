#!/bin/sh
set -eu

CEILINGS_APP_PASSWORD=$(cat /run/secrets/db_app_user)
CEILINGS_MIGRATION_PASSWORD=$(cat /run/secrets/db_migrator)
export CEILINGS_APP_PASSWORD CEILINGS_MIGRATION_PASSWORD

psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" \
    --set=ON_ERROR_STOP=1 --set="database=$POSTGRES_DB" <<'SQL'
\getenv app_password CEILINGS_APP_PASSWORD
\getenv migration_password CEILINGS_MIGRATION_PASSWORD
BEGIN;
CREATE ROLE app_user LOGIN PASSWORD :'app_password';
CREATE ROLE migrator LOGIN PASSWORD :'migration_password';
REVOKE ALL ON DATABASE :"database" FROM PUBLIC;
GRANT CONNECT ON DATABASE :"database" TO app_user, migrator;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
CREATE SCHEMA app AUTHORIZATION migrator;
GRANT USAGE ON SCHEMA app TO app_user;
ALTER DEFAULT PRIVILEGES FOR ROLE migrator IN SCHEMA app
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO app_user;
ALTER DEFAULT PRIVILEGES FOR ROLE migrator IN SCHEMA app
    GRANT USAGE, SELECT ON SEQUENCES TO app_user;
COMMIT;
SQL

unset CEILINGS_APP_PASSWORD CEILINGS_MIGRATION_PASSWORD
